"""
퀴즈 게임 프로그램 실행 진입점 (main.py)

프로젝트를 시작하는 메인 실행 파일(Entry Point)입니다.
터미널에서 'python main.py' 명령어로 실행하면 퀴즈 게임이 시작됩니다.

============================================================
[코딩 왕초보를 위한 프로젝트 복습 가이드]
============================================================
이 프로젝트는 기능별로 역할이 명확히 나뉜 모듈들로 구성되어 있습니다:

1. quiz.py (데이터 모델)
   - '퀴즈 1개'의 데이터(문제, 4지선다, 정답, 힌트, 해설)를 정의합니다.
   - Quiz 객체 <-> dict 상호 변환(to_dict, from_dict)을 담당합니다.

2. default_data.py (초기 데이터)
   - UEFA 챔피언스리그(UCL) 30개 기본 퀴즈와 초기 state 구조를 제공합니다.

3. storage.py (저장소/파일 입출력)
   - state.json 파일 읽기/쓰기를 안전하게 수행합니다.
   - 파일이 없거나 깨졌을 때 자동으로 기본 30문제로 복구합니다.

4. input_utils.py (입력 및 예외 처리)
   - 숫자(int), 텍스트(str), 예/아니오(y/n) 입력을 안전하게 검증합니다.
   - Ctrl+C(KeyboardInterrupt)나 EOF 입력 시 데이터 자동 저장 후 안전 종료합니다.

5. game.py (게임 진행 및 규칙 엔진)
   - QuizGame 클래스가 전체 메뉴, 문제 수 선택, 랜덤 섞기, 힌트 감점(0점 방어),
     점수 계산, 히스토리 저장 등 게임 전반을 총괄합니다.

6. main.py (실행 진입점)
   - QuizGame을 생성하고 실행(run)하는 출발선 역할을 합니다.
============================================================
"""

from game import QuizGame


def main() -> None:
    """
    프로그램의 메인 진입 함수입니다.
    QuizGame 객체를 생성하고 게임 루프(run)를 시작합니다.
    """
    game = QuizGame()
    game.run()


if __name__ == "__main__":
    # 이 파일이 터미널에서 직접 실행되었을 때만 main() 함수를 호출합니다.
    main()
